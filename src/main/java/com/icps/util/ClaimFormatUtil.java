package com.icps.util;

import java.math.BigDecimal;
import java.text.NumberFormat;
import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.Locale;

/**
 * Legacy-style static utility class providing currency formatting, date
 * formatting, and claim-reference-code generation/parsing used across
 * multiple unrelated layers of the application.
 *
 * This class intentionally has no Spring annotations and is never injected
 * as a dependency; it is called statically from controllers and services
 * alike (ClaimDetailController, Claims_Lifecycle_Service, Settlement_Service,
 * and ReportingRestController), consistent with the "static utility class
 * called from at least 3 classes" legacy code smell described in
 * Requirement 17.3.
 */
public class ClaimFormatUtil {

    private static final String CLAIM_REFERENCE_PREFIX = "CLM-";
    private static final int CLAIM_REFERENCE_DIGITS = 6;
    private static final String DATE_PATTERN = "MM/dd/yyyy";
    private static final String DATE_TIME_PATTERN = "MM/dd/yyyy HH:mm";

    /**
     * Private no-op constructor; this class is never instantiated.
     */
    private ClaimFormatUtil() {
    }

    /**
     * Formats a monetary amount as a US-locale currency string, e.g. "$1,234.56".
     *
     * @param amount the amount to format; may be null
     * @return the formatted currency string, or "$0.00" if amount is null
     */
    public static String formatCurrency(BigDecimal amount) {
        NumberFormat currencyFormat = NumberFormat.getCurrencyInstance(Locale.US);
        if (amount == null) {
            return currencyFormat.format(BigDecimal.ZERO);
        }
        return currencyFormat.format(amount);
    }

    /**
     * Formats a date using the "MM/dd/yyyy" pattern.
     *
     * @param date the date to format; may be null
     * @return the formatted date string, or an empty string if date is null
     */
    public static String formatDate(Date date) {
        if (date == null) {
            return "";
        }
        SimpleDateFormat dateFormat = new SimpleDateFormat(DATE_PATTERN);
        return dateFormat.format(date);
    }

    /**
     * Formats a date/time using the "MM/dd/yyyy HH:mm" pattern.
     *
     * @param date the date to format; may be null
     * @return the formatted date-time string, or an empty string if date is null
     */
    public static String formatDateTime(Date date) {
        if (date == null) {
            return "";
        }
        SimpleDateFormat dateTimeFormat = new SimpleDateFormat(DATE_TIME_PATTERN);
        return dateTimeFormat.format(date);
    }

    /**
     * Generates a human-readable claim reference code from a claim identifier,
     * e.g. claimId 1 becomes "CLM-000001".
     *
     * @param claimId the claim identifier; must not be null
     * @return the generated claim reference code
     * @throws IllegalArgumentException if claimId is null
     */
    public static String generateClaimReferenceCode(Long claimId) {
        if (claimId == null) {
            throw new IllegalArgumentException("claimId must not be null");
        }
        return CLAIM_REFERENCE_PREFIX + String.format("%0" + CLAIM_REFERENCE_DIGITS + "d", claimId);
    }

    /**
     * Parses a claim reference code generated by {@link #generateClaimReferenceCode(Long)}
     * back into its underlying claim identifier, e.g. "CLM-000001" becomes 1L.
     *
     * @param code the claim reference code to parse
     * @return the parsed claim identifier
     * @throws IllegalArgumentException if code is null, malformed, or does not
     *                                   start with the expected prefix
     */
    public static Long parseClaimReferenceCode(String code) {
        if (code == null || !code.startsWith(CLAIM_REFERENCE_PREFIX)) {
            throw new IllegalArgumentException("Malformed claim reference code: " + code);
        }
        String numericPart = code.substring(CLAIM_REFERENCE_PREFIX.length());
        if (numericPart.isEmpty()) {
            throw new IllegalArgumentException("Malformed claim reference code: " + code);
        }
        try {
            return Long.parseLong(numericPart);
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException("Malformed claim reference code: " + code, e);
        }
    }
}
